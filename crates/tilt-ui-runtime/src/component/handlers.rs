/// A template event delivered to a Rust `#[html_fn]` handler.
///
/// Templates can bind `onkeydown="handle_key"` or `(keydown)="handle_key()"`.
/// Pointer events expose `x`/`y` and optional `delta_x`/`delta_y`, drag
/// events additionally expose `distance_x`/`distance_y`, keyboard events
/// expose `key_code`/`key`/`text`/`repeat`, and scroll events expose `x`/`y`.
#[derive(Message, Debug, Clone, PartialEq, Eq)]
pub struct HtmlEvent {
    /// Entity on which the event originated.
    pub target: Entity,
    /// Normalized event name, such as `click` or `change`.
    pub kind: &'static str,
    /// Current value for editable and checkable controls, when applicable.
    pub value: Option<String>,
    /// Submit button for a form submission.
    pub submitter: Option<Entity>,
    /// Named event data (form fields, pointer coordinates, key details, or scroll position).
    pub data: BTreeMap<String, String>,
    /// Name of the registered Rust handler.
    pub handler: String,
}

/// Typed click payload accepted by `#[html_fn]`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HtmlClick {
    pub target: Entity,
}

impl TryFrom<HtmlEvent> for HtmlClick {
    type Error = ();
    fn try_from(event: HtmlEvent) -> Result<Self, Self::Error> {
        (event.kind == "click")
            .then_some(Self {
                target: event.target,
            })
            .ok_or(())
    }
}

/// Typed value-change payload accepted by `#[html_fn]`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HtmlChange {
    pub target: Entity,
    pub value: Option<String>,
}

impl TryFrom<HtmlEvent> for HtmlChange {
    type Error = ();
    fn try_from(event: HtmlEvent) -> Result<Self, Self::Error> {
        (event.kind == "change")
            .then_some(Self {
                target: event.target,
                value: event.value,
            })
            .ok_or(())
    }
}

/// Typed form-submit payload accepted by `#[html_fn]`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HtmlSubmit {
    pub target: Entity,
    pub submitter: Entity,
    pub data: BTreeMap<String, String>,
}

impl TryFrom<HtmlEvent> for HtmlSubmit {
    type Error = ();
    fn try_from(event: HtmlEvent) -> Result<Self, Self::Error> {
        if event.kind != "submit" {
            return Err(());
        }
        Ok(Self {
            target: event.target,
            submitter: event.submitter.ok_or(())?,
            data: event.data,
        })
    }
}

