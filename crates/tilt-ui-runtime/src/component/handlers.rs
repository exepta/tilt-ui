fn handler_for(
    event: &str,
    static_attributes: Option<&StaticAttributes>,
    bindings: Option<&EventBindings>,
) -> Option<String> {
    let handler = bindings
        .and_then(|bindings| {
            bindings
                .bindings
                .iter()
                .find(|binding| {
                    binding.name == event || binding.name.strip_prefix("on") == Some(event)
                })
                .map(|binding| binding.expression.clone())
        })
        .or_else(|| {
            static_attributes.and_then(|attributes| {
                attributes
                    .attributes
                    .iter()
                    .find(|attribute| attribute.name.strip_prefix("on") == Some(event))
                    .map(|attribute| attribute.value.clone())
            })
        });
    handler
        .map(|handler| {
            let handler = handler.trim();
            if handler.starts_with('$') || handler.contains(';') {
                handler.to_owned()
            } else {
                handler
                    .strip_suffix("()")
                    .unwrap_or(handler)
                    .trim()
                    .to_owned()
            }
        })
        .filter(|handler| !handler.is_empty())
}

fn forward_activations(
    mut source: MessageReader<ControlActivated>,
    elements: bevy::ecs::system::Query<(Option<&StaticAttributes>, Option<&EventBindings>)>,
    mut events: MessageWriter<HtmlEvent>,
) {
    for activation in source.read() {
        let Ok((attributes, bindings)) = elements.get(activation.entity) else {
            continue;
        };
        if let Some(handler) = handler_for("click", attributes, bindings) {
            events.write(HtmlEvent {
                target: activation.entity,
                kind: "click",
                value: None,
                submitter: None,
                data: BTreeMap::new(),
                handler,
            });
        }
    }
}

fn forward_checked(
    mut source: MessageReader<ControlCheckedChanged>,
    elements: bevy::ecs::system::Query<(Option<&StaticAttributes>, Option<&EventBindings>)>,
    mut events: MessageWriter<HtmlEvent>,
) {
    for change in source.read() {
        let Ok((attributes, bindings)) = elements.get(change.entity) else {
            continue;
        };
        if let Some(handler) = handler_for("change", attributes, bindings) {
            let mut data = BTreeMap::new();
            data.insert("checked".into(), change.checked.to_string());
            data.insert("selected".into(), change.checked.to_string());
            data.insert("value_type".into(), "boolean".into());
            events.write(HtmlEvent {
                target: change.entity,
                kind: "change",
                value: Some(change.checked.to_string()),
                submitter: None,
                data,
                handler,
            });
        }
    }
}

